CREATE TABLE IF NOT EXISTS stats (id INTEGER PRIMARY KEY CHECK (id = 1), visits INTEGER NOT NULL DEFAULT 0, views INTEGER NOT NULL DEFAULT 0, since TEXT);
CREATE TABLE IF NOT EXISTS places (
  k TEXT PRIMARY KEY, country TEXT NOT NULL, region TEXT, city TEXT,
  lat REAL NOT NULL, lon REAL NOT NULL, visits INTEGER NOT NULL DEFAULT 0, last TEXT, source TEXT NOT NULL DEFAULT 'live'
);
CREATE INDEX IF NOT EXISTS places_country ON places (country);
CREATE TABLE IF NOT EXISTS seen (h TEXT PRIMARY KEY, day TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS seen_day ON seen (day);
